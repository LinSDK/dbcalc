<#
.SYNOPSIS
  Regenerates data/dacs.js from the tray app's DAC plugins.

.DESCRIPTION
  Reads every ..\tray-app\plugins\<folder>\plugin.json (folders starting with "_" are skipped) and its measurements
  CSV, and writes data/dacs.js: one entry per DAC with its manifest fields and raw rows
  [interface, mode, volume step, volts]. The page combines rows per step with the median, as the tray app does.

  The output is a plain script (window.DBM_DACS = [...]) rather than JSON, so the page also works when opened
  straight from disk (file://), where fetch() isn't allowed.

.EXAMPLE
  pwsh calculator/scripts/sync-dacs.ps1
#>
param([string]$PluginsRoot)

$ErrorActionPreference = 'Stop'
$calc = Split-Path -Parent $PSScriptRoot
if (-not $PluginsRoot) { $PluginsRoot = Join-Path (Split-Path -Parent $calc) 'tray-app\plugins' }
$inv = [Globalization.CultureInfo]::InvariantCulture

function Read-Manifest([string]$path) {
    # plugin.json allows // comment lines and trailing commas; plain JSON parsers don't.
    $text = ((Get-Content $path) -notmatch '^\s*//') -join "`n"
    $text = [regex]::Replace($text, ',\s*([}\]])', '$1')
    $text | ConvertFrom-Json
}

$dacs = foreach ($dir in Get-ChildItem $PluginsRoot -Directory | Where-Object { $_.Name -notlike '_*' } | Sort-Object Name) {
    $manifestPath = Join-Path $dir.FullName 'plugin.json'
    if (-not (Test-Path $manifestPath)) { continue }
    $m = Read-Manifest $manifestPath
    $csvName = if ($m.measurements) { $m.measurements } else { 'measurements.csv' }
    $rows = foreach ($r in Import-Csv (Join-Path $dir.FullName $csvName)) {
        $volts = if ($r.PSObject.Properties['Voltage'] -and $r.Voltage) {
            [double]::Parse($r.Voltage, $inv)
        } else {
            $v = [double]::Parse($r.Output, $inv)
            if ($r.Unit -match '^\s*mV\s*$') { $v / 1000 } else { $v }
        }
        , @($r.Interface.Trim(), $r.Mode.Trim(), [int]$r.Volume, [math]::Round($volts, 6))
    }
    if (-not $rows) { Write-Warning "$($dir.Name): no measurement rows, skipped"; continue }
    [ordered]@{
        id           = $m.id
        name         = $m.name
        manufacturer = "$($m.manufacturer)"
        version      = "$($m.version)"
        description  = "$($m.description)"
        rows         = @($rows)
    }
    Write-Host "  $($m.name): $(@($rows).Count) rows"
}

$json = ConvertTo-Json @($dacs) -Depth 6 -Compress
$out = Join-Path $calc 'data\dacs.js'
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
@"
// Generated by scripts/sync-dacs.ps1 from tray-app/plugins on $(Get-Date -Format 'yyyy-MM-dd'). Don't edit by hand: re-run the script.
// Each DAC: manifest fields + rows of [interface, mode, volume step, volts RMS at 0 dBFS].
window.DBM_DACS = $json;
"@ | Set-Content $out -Encoding utf8NoBOM
Write-Host "Wrote $out ($(@($dacs).Count) DAC(s))" -ForegroundColor Green
